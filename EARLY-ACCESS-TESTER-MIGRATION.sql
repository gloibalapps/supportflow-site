-- Run once in Supabase SQL Editor before deploying build 257.
create table if not exists public.tester_activity_events (
  id bigint generated by default as identity primary key,
  device_ref text not null,
  access_code text,
  event_name text not null,
  app_version text,
  created_at timestamptz not null default now()
);
create index if not exists tester_activity_events_device_created_idx on public.tester_activity_events(device_ref, created_at desc);

create table if not exists public.tester_activity_status (
  device_ref text primary key,
  access_code text,
  status text not null default 'active',
  last_meaningful_at timestamptz,
  meaningful_actions integer not null default 0,
  feedback_submitted boolean not null default false,
  reward_qualifying boolean not null default false,
  reminder_sent_at timestamptz,
  grace_sent_at timestamptz,
  release_sent_at timestamptz,
  updated_at timestamptz not null default now()
);
-- Service-role Netlify functions access these tables. Do not expose tester telemetry to browser clients.
alter table public.tester_activity_events enable row level security;
alter table public.tester_activity_status enable row level security;
